"""Generate scs_own_tables.h from fw_tables.json (exact firmware tables used by scs_own.c)."""
import json, os, sys
H = os.path.dirname(os.path.abspath(__file__))
T = json.load(open(os.path.join(H, 'py', 'fw_tables.json')))
o = []
o.append('/* generated by gen_c_tables.py from fw_tables.json - do not edit */\n#include <stdint.h>\n')
def cstr(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
# exact frame tables: key = body as integer (4 or 8 bytes), value = messages joined by ' '
for name in ('EXT', 'ENERGY', 'CEN', 'MISC', 'AUX', 'INV'):
    rows = sorted((int(k, 16), len(k) // 2, ' '.join(v)) for k, v in T[name].items() if v)
    o.append('static const struct exact_row TBL_%s[] = {' % name)
    for k, n, v in rows:
        o.append('  {0x%XULL, %d, %s},' % (k, n, cstr(v)))
    o.append('};\n#define N_%s %d\n' % (name, len(rows)))
# value-byte tables for WHO 1/2 short frames: index = value byte -> "who what|who what"
for name in ('S_STATUS', 'S_POINT', 'S_GENERAL', 'S_AREA', 'S_GROUP'):
    o.append('static const char *TBL_%s[256] = {' % name)
    for v in range(256):
        e = T[name].get(str(v), [])
        o.append('  %s,' % (cstr('|'.join('%s %s' % (a, b) for a, b in e)) if e else 'NULL'))
    o.append('};\n')
rows = sorted(T['S_OTHER'].items())
o.append('static const struct other_row TBL_S_OTHER[] = {')
for k, v in rows:
    o.append('  {%s, %s},' % (cstr(k), cstr(' '.join(v))))
o.append('};\n#define N_S_OTHER %d\n' % len(rows))
open(os.path.join(H, 'scs_own_tables.h'), 'w').write('\n'.join(o))
print('ok', {n: len(T[n]) for n in T})
